import 'dart:convert';
import 'package:flutter/material.dart' as material;
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:flutter_quill/flutter_quill.dart' as quill;
import 'package:meducyte_app/features/observation/data/models/specialty_config.dart';
import 'package:meducyte_app/features/observation/data/models/specialty_localization.dart';
import 'package:meducyte_app/features/observation/data/providers/observation_providers.dart';

class PdfExportService {
  static String getPlainText(String? val) {
    if (val == null || val.trim().isEmpty) return '';
    try {
      if (val.trimLeft().startsWith('[')) {
        final doc = quill.Document.fromJson(jsonDecode(val));
        return doc.toPlainText().trim();
      }
    } catch (_) {}
    return val.trim();
  }

  static Future<void> exportToPdf({
    required material.BuildContext context,
    required SpecialtyFormConfig config,
    required PatientInfo patient,
    required String introduction,
    required String motif,
    required String histoire,
    required Antecedents antecedents,
    required Vitals vitals,
    required Map<String, String> physicalExam,
    required List<ExamFieldConfig> customPhysicalExamFields,
    required List<ParaclinicalExam> paraclinicalExams,
    required String resume,
    required String assessment,
  }) async {
    final pdf = pw.Document();
    final dateStr = DateFormat('dd/MM/yyyy HH:mm').format(DateTime.now());

    //Fonts
    final font = await PdfGoogleFonts.interRegular();
    final boldFont = await PdfGoogleFonts.interBold();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        theme: pw.ThemeData.withFont(base: font, bold: boldFont),
        header: (pw.Context pdfContext) {
          return pw.Column(
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'MEDUCYTE',
                        style: pw.TextStyle(
                          font: boldFont,
                          fontSize: 24,
                          color: PdfColors.blue900,
                        ),
                      ),
                      pw.Text(
                        'Your medical buddy',
                        style: const pw.TextStyle(
                          fontSize: 10,
                          color: PdfColors.grey700,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.end,
                    children: [
                      pw.Text(
                        config.specialty.localizedName(context).toUpperCase(),
                        style: pw.TextStyle(font: boldFont, fontSize: 14),
                      ),
                      pw.Text(dateStr, style: const pw.TextStyle(fontSize: 10)),
                    ],
                  ),
                ],
              ),
              pw.SizedBox(height: 10),
              pw.Divider(thickness: 1, color: PdfColors.grey400),
              pw.SizedBox(height: 20),
            ],
          );
        },
        footer: (pw.Context pdfContext) {
          return pw.Column(
            children: [
              pw.Divider(thickness: 0.5, color: PdfColors.grey400),
              pw.SizedBox(height: 5),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    'Generated by Meducyte App',
                    style: const pw.TextStyle(
                      fontSize: 8,
                      color: PdfColors.grey600,
                    ),
                  ),
                  pw.Text(
                    'Page${pdfContext.pageNumber} / ${pdfContext.pagesCount}',
                    style: const pw.TextStyle(
                      fontSize: 8,
                      color: PdfColors.grey600,
                    ),
                  ),
                ],
              ),
            ],
          );
        },
        build: (pw.Context pdfContext) {
          return [
            //Patient Info Section
            _buildSectionTitle('DONNÉES PATIENT', boldFont),
            pw.Container(
              padding: const pw.EdgeInsets.all(8),
              decoration: pw.BoxDecoration(
                color: PdfColors.grey100,
                borderRadius: pw.BorderRadius.circular(4),
              ),
              child: pw.Row(
                children: [
                  pw.Expanded(
                    child: _buildInfoItem(
                      'Âge',
                      patient.age.isEmpty ? 'N/A' : patient.age,
                      font,
                      boldFont,
                    ),
                  ),
                  pw.Expanded(
                    child: _buildInfoItem(
                      'Sexe',
                      patient.gender.isEmpty ? 'N/A' : patient.gender,
                      font,
                      boldFont,
                    ),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 15),

            //Introduction section
            if (introduction.isNotEmpty) ...[
              _buildSectionTitle('INTRODUCTION', boldFont),
              _buildQuillSection(introduction, font, boldFont),
              pw.SizedBox(height: 15),
            ],

            //Motif&Histoire
            if (motif.isNotEmpty) ...[
              _buildSectionTitle('MOTIF DE CONSULTATION', boldFont),
              _buildQuillSection(motif, font, boldFont),
              pw.SizedBox(height: 15),
            ],

            if (histoire.isNotEmpty) ...[
              _buildSectionTitle('HISTOIRE DE LA MALADIE', boldFont),
              _buildQuillSection(histoire, font, boldFont),
              pw.SizedBox(height: 15),
            ],

            //Antecedents
            if (anyAntecedent(antecedents)) ...[
              _buildSectionTitle('ANTÉCÉDENTS', boldFont),
              if (antecedents.medicaux.isNotEmpty) ...[
                _buildSubSectionTitle('Médicaux', boldFont),
                _buildQuillSection(
                  antecedents.medicaux,
                  font,
                  boldFont,
                  fontSize: 10,
                ),
              ],
              if (antecedents.chirurgicaux.isNotEmpty) ...[
                _buildSubSectionTitle('Chirurgicaux', boldFont),
                _buildQuillSection(
                  antecedents.chirurgicaux,
                  font,
                  boldFont,
                  fontSize: 10,
                ),
              ],
              if (antecedents.familiaux.isNotEmpty) ...[
                _buildSubSectionTitle('Familiaux', boldFont),
                _buildQuillSection(
                  antecedents.familiaux,
                  font,
                  boldFont,
                  fontSize: 10,
                ),
              ],
              if (antecedents.gynecoObstetriques.isNotEmpty) ...[
                _buildSubSectionTitle('Gynéco-Obstétriques', boldFont),
                _buildQuillSection(
                  antecedents.gynecoObstetriques,
                  font,
                  boldFont,
                  fontSize: 10,
                ),
              ],
              if (antecedents.modeDeVie.isNotEmpty) ...[
                _buildSubSectionTitle('Mode de Vie', boldFont),
                _buildQuillSection(
                  antecedents.modeDeVie,
                  font,
                  boldFont,
                  fontSize: 10,
                ),
              ],
              pw.SizedBox(height: 15),
            ],

            //Vitals
            _buildSectionTitle('SIGNES VITAUX', boldFont),
            pw.Wrap(
              spacing: 20,
              runSpacing: 8,
              children: [
                _buildVitalsItem(
                  'T°',
                  vitals.temperature,
                  '°C',
                  font,
                  boldFont,
                ),
                _buildVitalsItem(
                  'TA',
                  vitals.bloodPressure,
                  'mmHg',
                  font,
                  boldFont,
                ),
                _buildVitalsItem('FC', vitals.heartRate, 'bpm', font, boldFont),
                _buildVitalsItem(
                  'FR',
                  vitals.respiratoryRate,
                  '/min',
                  font,
                  boldFont,
                ),
                _buildVitalsItem(
                  'SpO2',
                  vitals.oxygenSaturation,
                  '%',
                  font,
                  boldFont,
                ),
              ],
            ),
            pw.SizedBox(height: 15),

            //Physical Exam
            if (physicalExam.isNotEmpty) ...[
              _buildSectionTitle('EXAMEN PHYSIQUE', boldFont),
              ...[...config.examFields, ...customPhysicalExamFields].map((
                field,
              ) {
                final value = physicalExam[field.key];
                if (value == null || value.isEmpty || value == '[]') {
                  return pw.SizedBox();
                }
                return pw.Padding(
                  padding: const pw.EdgeInsets.only(bottom: 8),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        field.label,
                        style: pw.TextStyle(
                          font: boldFont,
                          fontSize: 10,
                          color: PdfColors.grey900,
                        ),
                      ),
                      _buildQuillSection(value, font, boldFont, fontSize: 10),
                    ],
                  ),
                );
              }),
              pw.SizedBox(height: 15),
            ],

            //Paraclinical Exams
            if (paraclinicalExams.isNotEmpty) ...[
              _buildSectionTitle('EXAMENS COMPLÉMENTAIRES', boldFont),
              ...paraclinicalExams.map((exam) {
                return pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      exam.title,
                      style: pw.TextStyle(
                        font: boldFont,
                        fontSize: 11,
                        color: PdfColors.blue700,
                      ),
                    ),
                    pw.SizedBox(height: 4),
                    ...exam.parameters.map((param) {
                      if (param.value.isEmpty || param.value == '[]') {
                        return pw.SizedBox();
                      }
                      return pw.Padding(
                        padding: const pw.EdgeInsets.only(left: 12, bottom: 6),
                        child: pw.Column(
                          crossAxisAlignment: pw.CrossAxisAlignment.start,
                          children: [
                            pw.Text(
                              '${param.name} :',
                              style: pw.TextStyle(
                                font: boldFont,
                                fontSize: 10,
                                color: PdfColors.grey900,
                              ),
                            ),
                            _buildQuillSection(
                              param.value,
                              font,
                              boldFont,
                              fontSize: 10,
                            ),
                          ],
                        ),
                      );
                    }),
                    pw.SizedBox(height: 8),
                  ],
                );
              }),
              pw.SizedBox(height: 15),
            ],

            //Resume&Conclusion
            if (resume.isNotEmpty) ...[
              _buildSectionTitle('RÉSUMÉSYNDROMIQUE', boldFont),
              _buildQuillSection(resume, font, boldFont),
              pw.SizedBox(height: 15),
            ],

            if (assessment.isNotEmpty) ...[
              _buildSectionTitle('CONCLUSION/CONDUITEÀTENIR', boldFont),
              pw.Container(
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.blue900, width: 1),
                  borderRadius: pw.BorderRadius.circular(4),
                ),
                child: _buildQuillSection(assessment, font, boldFont),
              ),
              pw.SizedBox(height: 15),
            ],
          ];
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name:
          'Meducyte_Report_${DateFormat('yyyyMMdd_HHmm').format(DateTime.now())}.pdf',
    );
  }

  static bool anyAntecedent(Antecedents ant) {
    return ant.medicaux.isNotEmpty ||
        ant.chirurgicaux.isNotEmpty ||
        ant.familiaux.isNotEmpty ||
        ant.gynecoObstetriques.isNotEmpty ||
        ant.modeDeVie.isNotEmpty;
  }

  static pw.Widget _buildSubSectionTitle(String title, pw.Font boldFont) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(top: 4, bottom: 2),
      child: pw.Text(
        title,
        style: pw.TextStyle(
          font: boldFont,
          fontSize: 10,
          color: PdfColors.blue700,
        ),
      ),
    );
  }

  static pw.Widget _buildQuillSection(
    String? jsonStr,
    pw.Font font,
    pw.Font boldFont, {
    double fontSize = 11,
  }) {
    if (jsonStr == null || jsonStr.trim().isEmpty || jsonStr == '[]') {
      return pw.SizedBox();
    }

    if (!jsonStr.trimLeft().startsWith('[')) {
      return pw.Text(
        jsonStr.trim(),
        style: pw.TextStyle(font: font, fontSize: fontSize),
      );
    }

    try {
      final List<dynamic> deltaJson = jsonDecode(jsonStr);
      final doc = quill.Document.fromJson(deltaJson);
      final List<pw.Widget> widgets = [];

      for (final node in doc.root.children) {
        if (node is quill.Line) {
          widgets.add(_buildQuillLine(node, font, boldFont, fontSize));
        } else if (node is quill.Block) {
          for (final line in node.children) {
            if (line is quill.Line) {
              widgets.add(
                _buildQuillLine(
                  line,
                  font,
                  boldFont,
                  fontSize,
                  isListItem: true,
                ),
              );
            }
          }
        }
      }

      return pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: widgets,
      );
    } catch (_) {
      //Fallback to plain text if JSON parsing fails
      return pw.Text(
        jsonStr,
        style: pw.TextStyle(font: font, fontSize: fontSize),
      );
    }
  }

  static pw.Widget _buildQuillLine(
    quill.Line line,
    pw.Font font,
    pw.Font boldFont,
    double baseFontSize, {
    bool isListItem = false,
  }) {
    final spans = <pw.TextSpan>[];
    final attrs = line.style.attributes;

    double currentFontSize = baseFontSize;
    pw.Font currentBaseFont = font;

    if (attrs.containsKey('header')) {
      final level = attrs['header']!.value;
      if (level == 1) {
        currentFontSize = baseFontSize * 1.4;
        currentBaseFont = boldFont;
      } else if (level == 2) {
        currentFontSize = baseFontSize * 1.2;
        currentBaseFont = boldFont;
      }
    }

    for (final leaf in line.children) {
      if (leaf is quill.Leaf) {
        final leafAttrs = leaf.style.attributes;
        final isBold = leafAttrs.containsKey('bold');
        final isItalic = leafAttrs.containsKey('italic');

        spans.add(
          pw.TextSpan(
            text: leaf.toPlainText(),
            style: pw.TextStyle(
              font: isBold ? boldFont : currentBaseFont,
              fontSize: currentFontSize,
              fontStyle: isItalic ? pw.FontStyle.italic : pw.FontStyle.normal,
            ),
          ),
        );
      }
    }

    final richText = pw.RichText(text: pw.TextSpan(children: spans));

    if (isListItem || attrs.containsKey('list')) {
      return pw.Padding(
        padding: const pw.EdgeInsets.only(left: 12, bottom: 2, top: 2),
        child: pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              '• ',
              style: pw.TextStyle(font: boldFont, fontSize: currentFontSize),
            ),
            pw.Expanded(child: richText),
          ],
        ),
      );
    }

    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 2),
      child: richText,
    );
  }

  static pw.Widget _buildSectionTitle(String title, pw.Font boldFont) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          title,
          style: pw.TextStyle(
            font: boldFont,
            fontSize: 12,
            color: PdfColors.blue900,
          ),
        ),
        pw.SizedBox(height: 4),
        pw.Container(height: 1, color: PdfColors.blue900, width: 30),
        pw.SizedBox(height: 8),
      ],
    );
  }

  static pw.Widget _buildInfoItem(
    String label,
    String value,
    pw.Font font,
    pw.Font boldFont,
  ) {
    return pw.RichText(
      text: pw.TextSpan(
        children: [
          pw.TextSpan(
            text: '$label: ',
            style: pw.TextStyle(font: boldFont, fontSize: 11),
          ),
          pw.TextSpan(
            text: value,
            style: pw.TextStyle(font: font, fontSize: 11),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildVitalsItem(
    String label,
    String value,
    String unit,
    pw.Font font,
    pw.Font boldFont,
  ) {
    if (value.isEmpty) return pw.SizedBox();
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 4),
      decoration: pw.BoxDecoration(
        color: PdfColors.blue50,
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.RichText(
        text: pw.TextSpan(
          children: [
            pw.TextSpan(
              text: '$label: ',
              style: pw.TextStyle(
                font: boldFont,
                fontSize: 10,
                color: PdfColors.blue900,
              ),
            ),
            pw.TextSpan(
              text: '$value$unit',
              style: pw.TextStyle(
                font: font,
                fontSize: 10,
                color: PdfColors.black,
              ),
            ),
          ],
        ),
      ),
    );
  }
}
